#!/usr/bin/env node
// Writes lib/expected-migrations.generated.ts: the sorted folder names under prisma/migrations, bundled into the
// build so the startup schema guard never reads the filesystem at runtime (Vercel functions do not ship prisma/).
// Wired into `npm run build`. Pass --check to verify the committed file is current without writing.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "prisma", "migrations");
const out = path.join(root, "lib", "expected-migrations.generated.ts");

const names = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const body =
  "// GENERATED by scripts/gen-expected-migrations.mjs (runs in `npm run build`). Do not edit by hand.\n" +
  "export const EXPECTED_MIGRATIONS: readonly string[] = " +
  JSON.stringify(names, null, 2) +
  ";\n";

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== body) {
    console.error("lib/expected-migrations.generated.ts is stale; run node scripts/gen-expected-migrations.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
  console.log(`expected-migrations: ${names.length} migrations`);
}
