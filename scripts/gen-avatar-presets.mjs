// Writes lib/avatar-presets.generated.ts from the files in public/avatars (owner 2026-11-14): every <name>-1024.webp
// there is a preset. Runs in `npm run build` and after scripts/avatars-build.mjs, so a new avatar joins the lists by
// itself. Profit list: the owner's order, then any other avatar (A-Z); bear is the loss avatar only. Loss list: bear
// first, then the profit list.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PROFIT_ORDER = ["coin_crown", "coin_laurel", "samurai_moon", "samurai_sun", "bull", "wolf", "phoenix", "owl", "silhouette", "gentleman", "trader", "dragon", "ninja"];
const LOSS_FIRST = "bear";
// the card colour behind each avatar (share-card-prototype.html BG); a new avatar takes the card's base colour
const BG = { coin_crown: "#120E07", coin_laurel: "#0E0C08", samurai_moon: "#120E07", samurai_sun: "#0E0A09", bull: "#120E07", wolf: "#070C16", phoenix: "#140804", owl: "#0F0E0C", silhouette: "#0A0A0A", gentleman: "#0A0F1E", trader: "#06101F", dragon: "#120607", ninja: "#0B0B0C", bear: "#120707" };
const BASE_BG = "#0B0B0C";

export function avatarLists(names) {
  const set = new Set(names);
  const profit = [...PROFIT_ORDER.filter((n) => set.has(n)), ...[...set].filter((n) => !PROFIT_ORDER.includes(n) && n !== LOSS_FIRST).sort()];
  const loss = [...(set.has(LOSS_FIRST) ? [LOSS_FIRST] : []), ...profit];
  return { profit, loss };
}

export async function genAvatarPresets(root = process.cwd()) {
  const dir = path.join(root, "public", "avatars");
  const names = existsSync(dir) ? readdirSync(dir).map((f) => /^([a-z0-9_]+)-1024\.webp$/.exec(f)?.[1]).filter(Boolean) : [];
  const { profit, loss } = avatarLists(names);
  const bg = Object.fromEntries([...new Set([...profit, ...loss])].map((n) => [n, BG[n] ?? BASE_BG]));
  const body =
    "// GENERATED by scripts/gen-avatar-presets.mjs (runs in `npm run build`) from public/avatars. Do not edit by hand.\n" +
    `export const AVATAR_PROFIT = ${JSON.stringify(profit)} as const;\n` +
    `export const AVATAR_LOSS = ${JSON.stringify(loss)} as const;\n` +
    `export const AVATAR_BG: Record<string, string> = ${JSON.stringify(bg)};\n`;
  writeFileSync(path.join(root, "lib", "avatar-presets.generated.ts"), body);
  console.log(`avatar-presets: ${profit.length} profit, ${loss.length} loss`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await genAvatarPresets();
