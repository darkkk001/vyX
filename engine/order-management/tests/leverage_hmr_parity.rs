//! Leverage rules + HMR plugin (owner spec 2026-11-06): the parity oracle.
//!
//! Asserts that the engine gives the SAME answer as the web for every case in `tests/leverage-hmr-vectors.json` (a copy of the web branch's docs/contracts/leverage-hmr-vectors.json):
//!
//! - `open_leverage`: the effective leverage of a NEW position (`hmr::effective_open_leverage`) -- min of the account's leverage, the
//!   group maximum and every active HMR window touching the symbol -- the figure stored as `Position.openLeverage`, the window that
//!   set it, and the refusal sentence that names it;
//! - `margin`: the used margin with a per-position leverage (`position.openLeverage ?? account.leverage`, `calc::used_margin`) and the
//!   whole pre-trade margin decision for an order whose leverage a window set (`calc::pre_trade_margin_decision`).
//!
//! The expectations are not written here. The file is generated by `scripts/contracts/gen-leverage-hmr-vectors.ts` from the WEB's own
//! functions (lib/hmr.ts, lib/margin.ts), the same direction as gate-vectors.json: the web is the oracle. No database.

use chrono::{DateTime, Utc};
use order_management::{calc, db, hmr};
use protocol::OrderSide;
use rust_decimal::Decimal;
use std::collections::{HashMap, HashSet};
use std::str::FromStr;

fn vectors() -> serde_json::Value {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/leverage-hmr-vectors.json");
    serde_json::from_str(&std::fs::read_to_string(path).expect("leverage-hmr-vectors.json")).unwrap()
}

fn text(v: &serde_json::Value) -> &str {
    v.as_str().expect("a required string")
}
fn dec(v: &serde_json::Value) -> Decimal {
    Decimal::from_str(text(v)).expect("a decimal string")
}
fn dec_opt(v: &serde_json::Value) -> Option<Decimal> {
    v.as_str().map(|s| Decimal::from_str(s).expect("a decimal string"))
}
fn at(v: &serde_json::Value) -> DateTime<Utc> {
    DateTime::parse_from_rfc3339(text(v)).expect("an ISO instant").with_timezone(&Utc)
}
fn side(v: &serde_json::Value) -> OrderSide {
    match text(v) {
        "BUY" => OrderSide::Buy,
        "SELL" => OrderSide::Sell,
        other => panic!("unknown side {other}"),
    }
}
fn u32_opt(v: &serde_json::Value) -> Option<u32> {
    v.as_u64().map(|n| n as u32)
}

fn state_of(i: &serde_json::Value) -> hmr::HmrState {
    hmr::HmrState {
        enabled: i["hmrEnabled"].as_bool().unwrap(),
        windows: i["windows"]
            .as_array()
            .unwrap()
            .iter()
            .map(|w| hmr::HmrWindow {
                currency: text(&w["currency"]).to_string(),
                starts_at: at(&w["startsAt"]),
                ends_at: at(&w["endsAt"]),
                leverage: w["leverage"].as_u64().unwrap() as u32,
                enabled: w["enabled"].as_bool().unwrap(),
            })
            .collect(),
        symbols_by_currency: i["correlations"]
            .as_object()
            .unwrap()
            .iter()
            .map(|(c, s)| (c.clone(), s.as_array().unwrap().iter().map(|x| text(x).to_string()).collect::<HashSet<_>>()))
            .collect::<HashMap<_, _>>(),
    }
}

#[test]
fn the_effective_open_leverage_agrees_with_the_web_on_every_case() {
    let v = vectors();
    let cases = v["open_leverage"].as_array().expect("open_leverage cases");
    assert!(cases.len() >= 15, "the vector file lost its cases");
    for c in cases {
        let (i, e) = (&c["input"], &c["expect"]);
        let note = text(&i["note"]);
        let got = hmr::effective_open_leverage(
            i["accountLeverage"].as_u64().unwrap() as u32,
            u32_opt(&i["groupMax"]),
            &state_of(i),
            text(&i["symbol"]),
            at(&i["now"]),
        );
        assert_eq!(got.leverage as u64, e["leverage"].as_u64().unwrap(), "leverage: {note}");
        assert_eq!(got.open_leverage, u32_opt(&e["openLeverage"]), "openLeverage: {note}");
        match (&got.hmr, e["hmr"].is_null()) {
            (None, true) => assert!(e["refusalText"].is_null(), "{note}"),
            (Some(h), false) => {
                assert_eq!(h.currency, text(&e["hmr"]["currency"]), "currency: {note}");
                assert_eq!(h.leverage as u64, e["hmr"]["leverage"].as_u64().unwrap(), "window leverage: {note}");
                assert_eq!(h.ends_at, at(&e["hmr"]["endsAt"]), "endsAt: {note}");
                // the refusal sentence is compared word for word: the trader reads it
                assert_eq!(hmr::refusal_text(h), text(&e["refusalText"]), "refusal text: {note}");
            }
            (got, _) => panic!("hmr binding differs: engine {got:?} vs web {} -- {note}", e["hmr"]),
        }
    }
}

fn positions_of(i: &serde_json::Value) -> Vec<db::OpenPositionWithMarket> {
    i["positions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|p| {
            let price = dec(&p["price"]);
            let rate = dec_opt(&p["rate"]);
            db::OpenPositionWithMarket {
                id: String::new(),
                symbol: text(&p["symbol"]).to_string(),
                side: side(&p["side"]),
                volume: dec(&p["volume"]),
                open_price: dec(&p["openPrice"]),
                contract_size: dec(&p["contractSize"]),
                bid: Some(price),
                ask: Some(price),
                sl_price: None,
                tp_price: None,
                sl_amount: None,
                tp_amount: None,
                fx_rate: rate.unwrap_or(Decimal::ONE),
                rate_missing: rate.is_none(),
                hedged_margin_pct: dec(&p["hedgedMarginPct"]),
                ask_rule: None,
                open_leverage: u32_opt(&p["openLeverage"]),
                quote: None,
            }
        })
        .collect()
}

#[test]
fn margin_with_a_per_position_leverage_agrees_with_the_web_on_every_case() {
    let v = vectors();
    let cases = v["margin"].as_array().expect("margin cases");
    assert!(cases.len() >= 10, "the vector file lost its cases");
    for c in cases {
        let (i, e) = (&c["input"], &c["expect"]);
        let note = text(&i["note"]);
        let state = calc::AccountState {
            effective_balance: dec(&i["balance"]),
            credit: dec(&i["credit"]),
            leverage: i["leverage"].as_u64().unwrap() as u32,
            positions: positions_of(i),
        };
        // the used margin of what is open: each position at its OWN leverage
        if !e["usedMargin"].is_null() {
            assert_eq!(calc::used_margin(&state), dec(&e["usedMargin"]), "used margin: {note}");
        }
        let o = &i["newOrder"];
        let symbol = text(&o["symbol"]).to_string();
        let leg = calc::NewLeg {
            symbol: &symbol,
            side: side(&o["side"]),
            volume: dec(&o["volume"]),
            contract_size: dec(&o["contractSize"]),
            fill_price: dec(&o["fillPrice"]),
            fx_rate: dec_opt(&o["rate"]),
            hedged_margin_pct: dec(&o["hedgedMarginPct"]),
            open_leverage: u32_opt(&o["leverage"]),
        };
        let got = calc::pre_trade_margin_decision(&state, &leg, dec(&i["marginCallLevel"]));
        assert_eq!(got.as_deref(), e["reject"].as_str(), "pre-trade verdict: {note}");
    }
}

#[test]
fn a_refusal_that_a_window_caused_names_the_window() {
    let h = hmr::HmrBinding {
        currency: "USD".into(),
        ends_at: DateTime::parse_from_rfc3339("2026-11-06T14:30:00Z").unwrap().with_timezone(&Utc),
        leverage: 20,
        symbol: "XAUUSD".into(),
    };
    assert_eq!(
        hmr::margin_refusal_with_hmr("INSUFFICIENT_MARGIN", &h),
        "Not enough free margin for this order. HMR in effect for USD until 14:30 UTC: leverage 1:20 on new XAUUSD positions."
    );
    assert_eq!(
        hmr::margin_refusal_with_hmr("INSUFFICIENT_BALANCE", &h),
        "Not enough balance for this order. HMR in effect for USD until 14:30 UTC: leverage 1:20 on new XAUUSD positions."
    );
}
