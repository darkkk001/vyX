-- PRIORITY 1 (FAILOVER): the client's OWN idempotency key goes into the engine's "Order" row.
--
-- THE PROBLEM THIS SOLVES, exactly. The failover story is "engine down -> the web fills it, with no
-- trader impact and no double fill". Two of those three were already true. The third was not, and the
-- reason was one expression in this function: the order row was written with
--     'engine:' || p_order_id
-- as its idempotencyKey -- unique, never colliding, and USELESS to anyone holding the client's key.
--
-- So the dangerous case had no answer. The web guard forwards an order, the engine commits the fill,
-- and the ANSWER is lost (a timeout, a dropped connection, the gateway restarting). The guard cannot
-- tell "filled" from "never arrived". Filling again would double the position; refusing leaves the
-- trader staring at an error over a position that exists. The cutover design calls this out as the
-- worse of its two failure modes (section 5b.3) and the guard chose the safe half: it returned 502 and
-- never filled again. Correct, but the trader still saw a failure.
--
-- WITH THE CLIENT'S KEY IN THIS ROW, that whole case collapses into a lookup the web already does.
-- app/api/trade/orders/route.ts opens every fill with
--     prisma.order.findUnique({ where: { accountId_idempotencyKey: ... } })
-- and returns the existing order when it hits. Once the engine writes the same key, that read FINDS
-- THE ENGINE'S FILL, and a lost answer becomes a 200 carrying the real order.
--
-- AND IT IS A CONSTRAINT, NOT A CHECK. "Order" has @@unique([accountId, idempotencyKey]). This
-- function's INSERT is in the same transaction as the position, the deal and the ledger, so if the web
-- ever does fill the same key first, the engine's INSERT raises 23505 and THE ENTIRE FILL ROLLS BACK --
-- order, position, deal and all. The no-double-fill property is therefore enforced by Postgres on both
-- sides of the race, not by the two services agreeing about who went first. That is the whole point of
-- threading the key rather than adding a pre-flight check: a check can be raced, a unique index cannot.
--
-- NULL IS STILL ALLOWED, and still means what it used to. An order that originates at the engine's own
-- HTTP route (a load test, the parallel-run harness, any caller that is not the web guard) has no
-- client key, and COALESCE keeps the old 'engine:' || p_order_id for it. Those orders were never
-- retryable by key and are not made less so here.
--
-- The body below is UNCHANGED from 20261103200000 apart from that one COALESCE and the new parameter.
-- It is generated from that file rather than retyped, so the twelve statements, their order and their
-- text are the same ones engine/order-management/tests/open_position_depth_db.rs proves row-identical.
--
-- Dropping the 22-argument form rather than leaving it beside the new one: two overloads differing only
-- in a trailing text would make every call site's resolution depend on argument counting, and the one
-- thing this function must never be is ambiguous about which body ran.
DROP FUNCTION IF EXISTS vyx_open_position(text,text,text,text,text,text,text,text,text,text,numeric,numeric,numeric,numeric,numeric,numeric,text,text,numeric,text,text,boolean);

CREATE OR REPLACE FUNCTION vyx_open_position(
  -- the ids, generated by the caller: it has to be able to name the order in a rejection even when
  -- this function never runs, and a test has to be able to predict them
  p_order_id        text,
  p_position_id     text,
  p_deal_id         text,
  p_transaction_id  text,
  p_effect_id       text,
  -- the order
  p_broker_id       text,
  p_account_id      text,
  p_symbol_id       text,
  p_side            text,
  p_order_type      text,
  p_volume          numeric,
  p_requested_price numeric,
  p_sl_price        numeric,
  p_tp_price        numeric,
  -- the fill
  p_fill_price      numeric,
  p_filled_volume   numeric,
  p_routing         text,
  p_book_type       text,
  -- the money, already decided in Rust (commission_per_lot x volume, and the note's exact wording)
  p_commission      numeric,
  p_commission_note text,
  -- the deal
  p_deal_reason     text,
  -- true: this path owns the "Order" row and creates it here (the engine's own market entry point).
  -- false: the row already exists and is PENDING -- a resting LIMIT/STOP being triggered, or (the
  -- cutover's end state, design section 5b.2) one the WEB created for the engine to fill.
  p_create_order    boolean,

  -- PRIORITY 1 (failover): the CLIENT's idempotency key, forwarded by the web guard through the
  -- gateway. NULL for a caller that has none. Last in the list so every existing positional bind in
  -- db.rs keeps its number.
  p_idempotency_key text DEFAULT NULL
)
RETURNS TABLE (
  order_id               text,
  position_id            text,
  opened_at              timestamptz,
  deal_id                text,
  group_category_at_open text,
  commission_charged     numeric,
  effect_enqueued        boolean
)
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_opened_at      timestamptz;
  v_balance_before numeric;
  v_balance_after  numeric;
  v_source         text;
  v_category       text;
  v_origin_order   text;
  v_deal_broker    text;
  v_deal_account   text;
  v_deal_symbol    text;
  v_deal_side      text;
  v_deal_volume    numeric;
  v_deal_price     numeric;
  v_commission_sum numeric;
  v_commission_rows bigint;
  v_only_txn       text;
  v_effect_rows    integer;
BEGIN
  -- 1. db::insert_order, Book::Prisma. 'PENDING' because that is what a resting order is on this book
  -- and what every pending scan matches; 'API' because these orders arrive through the engine's HTTP
  -- routes and WEB (the column default) would misattribute them in reports. idempotencyKey is the
  -- CLIENT's key when the web guard forwarded one -- that is what lets a lost answer be found again --
  -- and falls back to the row's own id for a caller that has none.
  IF p_create_order THEN
    INSERT INTO "Order"
      (id, "brokerId", "accountId", "symbolId", side, type, volume,
       "requestedPrice", "slPrice", "tpPrice", status, "idempotencyKey", source, "updatedAt")
    VALUES (p_order_id, p_broker_id, p_account_id, p_symbol_id, p_side::"OrderSide", p_order_type::"OrderType", p_volume,
            p_requested_price, p_sl_price, p_tp_price,
            'PENDING'::"OrderStatus", COALESCE(p_idempotency_key, 'engine:' || p_order_id), 'API'::"OrderSource", now());
  END IF;

  -- 2. db::set_filled. The compare-and-set. Unreachable when this call created the row above -- no
  -- other writer can see it yet -- and kept for the two cases where it is not: a resting order two
  -- ticks race for, and the web's own fill path during a failover. Losing it must leave NOTHING
  -- behind, which is what raising here does: the whole statement, order row included, rolls back.
  -- The Rust path reached the same state with tx.rollback(); this is that, expressed as an error the
  -- caller maps back to "the order was already answered by another writer".
  UPDATE "Order" SET status = 'FILLED'::"OrderStatus", "filledPrice" = p_fill_price,
         "filledAt" = now(), "executedAt" = now(),
         "executionMode" = COALESCE("executionMode", 'AUTO'),
         routing = COALESCE(p_routing, routing), "updatedAt" = now()
   WHERE id = p_order_id AND status = 'PENDING'::"OrderStatus";
  IF NOT FOUND THEN
    RAISE EXCEPTION 'vyx_open_position: order % was already answered', p_order_id
      USING ERRCODE = 'VYX01';
  END IF;

  -- 3. db::insert_position. Names neither `ticket` nor `groupCategoryAtOpen` (both triggers fill them)
  -- and not `status` either (it defaults to OPEN). `openedAt` is read back because the IN deal's
  -- executedAt must be that exact value, as lib/deals.ts reads it off the position for the same reason.
  INSERT INTO "Position"
    (id, "brokerId", "accountId", "symbolId", "originOrderId", side, volume, "openPrice", "slPrice", "tpPrice", "bookType")
  VALUES (p_position_id, p_broker_id, p_account_id, p_symbol_id, p_order_id, p_side::"OrderSide", p_filled_volume,
          p_fill_price, p_sl_price, p_tp_price, p_book_type::"BookType")
  RETURNING "openedAt" INTO v_opened_at;

  -- 4. db::record_commission, Book::Prisma. A zero or negative per-lot rate charges nothing at all --
  -- the web's own lte(0). FOR NO KEY UPDATE, not FOR UPDATE: the lock lib/account-lock.ts takes, which
  -- serialises writers to the row without blocking the FK references the inserts below need.
  IF p_commission > 0 THEN
    SELECT balance INTO v_balance_before FROM "Account" WHERE id = p_account_id FOR NO KEY UPDATE;
    v_balance_after := v_balance_before - p_commission;

    UPDATE "Account" SET balance = v_balance_after, "updatedAt" = now() WHERE id = p_account_id;

    INSERT INTO "Transaction"
      (id, "brokerId", "accountId", type, status, amount, "balanceBefore", "balanceAfter",
       "referenceType", "referenceId", note, "updatedAt")
    VALUES (p_transaction_id, p_broker_id, p_account_id, 'COMMISSION'::"TransactionType", 'COMPLETED'::"TransactionStatus",
            -p_commission, v_balance_before, v_balance_after, 'Position', p_position_id, p_commission_note, now());

    UPDATE "Position" SET commission = commission + p_commission WHERE id = p_position_id;
  END IF;

  -- 5. db::write_open_deal. Read back rather than taken from the parameters, exactly as the Rust path
  -- did: `source` belongs to the order (which this call may not have created) and
  -- `groupCategoryAtOpen` to the trigger, so neither may be assumed.
  SELECT p."brokerId", p."accountId", p."symbolId", p.side::text, p.volume, p."openPrice",
         p."openedAt", p."originOrderId", o.source::text, p."groupCategoryAtOpen"::text
    INTO v_deal_broker, v_deal_account, v_deal_symbol, v_deal_side, v_deal_volume, v_deal_price,
         v_opened_at, v_origin_order, v_source, v_category
    FROM "Position" p JOIN "Order" o ON o.id = p."originOrderId"
   WHERE p.id = p_position_id;

  -- the commission is SUMMED back out of the ledger, never passed in: the Transaction rows are the
  -- record, so the deal can never disagree with the money that actually moved. The sum is NEGATIVE.
  -- transactionId is set only when there is exactly ONE row -- the column is UNIQUE, so two deals
  -- cannot name one transaction, and with several rows there is no single one to name.
  SELECT COALESCE(SUM(amount), 0), count(*), CASE WHEN count(*) = 1 THEN min(id) END
    INTO v_commission_sum, v_commission_rows, v_only_txn
    FROM "Transaction"
   WHERE "referenceType" = 'Position' AND "referenceId" = p_position_id AND type = 'COMMISSION'::"TransactionType";

  INSERT INTO "Deal"
    (id, "brokerId", "accountId", "positionId", "orderId", "symbolId", side, entry, reason, source,
     volume, price, commission, "transactionId", "executedAt")
  VALUES (p_deal_id, v_deal_broker, v_deal_account, p_position_id, v_origin_order, v_deal_symbol,
          v_deal_side::"OrderSide", 'IN'::"DealEntry", p_deal_reason::"DealReason", v_source::"OrderSource",
          v_deal_volume, v_deal_price, v_commission_sum, v_only_txn, v_opened_at);

  UPDATE "Position" SET "initialVolume" = volume WHERE id = p_position_id;

  -- 6. db::enqueue_position_opened. The hedge is the WEB's to place; the engine only says a position
  -- opened on the A book. Gated on the category the TRIGGER wrote, read back above -- never on the
  -- engine's guess, because a missed stamp must not be hedged.
  v_effect_rows := 0;
  IF v_category = 'A_BOOK' THEN
    INSERT INTO "PostCloseEffect" (id, kind, "dedupeKey", "brokerId", "accountId", "positionId", payload)
    VALUES (p_effect_id, 'POSITION_OPENED', 'open:' || p_position_id || ':' || p_deal_id,
            v_deal_broker, v_deal_account, p_position_id, jsonb_build_object('dealId', p_deal_id))
    ON CONFLICT ("dedupeKey") DO NOTHING;
    GET DIAGNOSTICS v_effect_rows = ROW_COUNT;
  END IF;

  RETURN QUERY SELECT p_order_id, p_position_id, v_opened_at, p_deal_id, v_category,
                      CASE WHEN p_commission > 0 THEN p_commission ELSE 0::numeric END,
                      v_effect_rows = 1;
END;
$$;

COMMENT ON FUNCTION vyx_open_position IS
  'L2 Step 2 + failover: the engine''s whole open-position write transaction in one round trip, under the client''s own idempotency key so a lost answer is recoverable and a double fill is refused by the unique index. The same twelve statements db.rs issued, in the same order, so every row and every trigger is unchanged. Proved row-for-row by engine/order-management/tests/open_position_depth_db.rs.';
